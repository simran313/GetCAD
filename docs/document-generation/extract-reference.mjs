#!/usr/bin/env node
/**
 * Regenerates the code-derived reference chapters of the Master Technical
 * Handbook from the repository itself, so they always match the audited
 * revision:
 *
 *   docs/database/generated/schema.md      tables, columns, keys, RLS, policies, triggers, grants
 *   docs/database/generated/functions.md   database functions, security mode, who may call them
 *   docs/api/generated/routes.md           every page and API route, its guard and HTTP methods
 *   docs/api/generated/server-actions.md   every server action and the database functions it calls
 *   docs/architecture/generated/environment.md   configuration variable NAMES (never values)
 *
 * The database part applies db/migrations then db/policies to a THROWAWAY
 * local Postgres database it creates and drops itself. It refuses any host
 * that is not local, the same guard as the test harness.
 *
 *   DATABASE_URL=postgres://postgres@127.0.0.1:5433/postgres node docs/document-generation/extract-reference.mjs
 */
import { execSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

import pg from "pg";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const ADMIN_URL = process.env.DATABASE_URL ?? "postgres://postgres@127.0.0.1:5433/postgres";
const LOCAL = new Set(["localhost", "127.0.0.1", "::1", "[::1]"]);
const host = new URL(ADMIN_URL).hostname;
if (!LOCAL.has(host)) {
  console.error(`Refusing: DATABASE_URL points at "${host}". This script creates and drops a database; local only.`);
  process.exit(1);
}
const SCRATCH_DB = "tcp_handbook_extract";
const sha = execSync("git rev-parse --short HEAD", { cwd: ROOT }).toString().trim();
const banner = (title) =>
  `<!-- GENERATED by docs/document-generation/extract-reference.mjs at commit ${sha}. Do not edit by hand; re-run the script. -->\n\n# ${title}\n\n> Generated from the repository at commit \`${sha}\`. Every row below is read from the code or from a database built from \`db/migrations\` and \`db/policies\`, not written by hand.\n\n`;
const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
const write = (rel, text) => {
  const p = join(ROOT, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, text);
  console.log(`wrote ${rel}`);
};

// ---------------------------------------------------------------- database
async function database() {
  const admin = new pg.Client({ connectionString: ADMIN_URL });
  await admin.connect();
  await admin.query(`DROP DATABASE IF EXISTS ${SCRATCH_DB}`);
  await admin.query(`CREATE DATABASE ${SCRATCH_DB}`);
  const url = new URL(ADMIN_URL);
  url.pathname = `/${SCRATCH_DB}`;
  const db = new pg.Client({ connectionString: url.toString() });
  await db.connect();
  try {
    await db.query("DROP SCHEMA IF EXISTS public CASCADE; CREATE SCHEMA public;");
    const files = ["migrations", "policies"].flatMap((d) =>
      readdirSync(join(ROOT, "db", d)).filter((f) => f.endsWith(".sql")).sort().map((f) => join(ROOT, "db", d, f)),
    );
    for (const f of files) await db.query(readFileSync(f, "utf8"));
    const q = async (sql) => (await db.query(sql)).rows;

    const tables = await q(`
      SELECT n.nspname AS schema, c.relname AS name, c.relrowsecurity AS rls, c.relforcerowsecurity AS forced,
             obj_description(c.oid) AS comment, c.oid
        FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
       WHERE c.relkind IN ('r','p') AND n.nspname IN ('public','app','audit')
       ORDER BY 1, 2`);
    const cols = await q(`
      SELECT table_schema AS schema, table_name AS t, column_name AS c, data_type, udt_name, is_nullable, column_default, is_generated
        FROM information_schema.columns WHERE table_schema IN ('public','app','audit') ORDER BY table_schema, table_name, ordinal_position`);
    const cons = await q(`
      SELECT n.nspname AS schema, cl.relname AS t, co.conname, co.contype, pg_get_constraintdef(co.oid) AS def
        FROM pg_constraint co JOIN pg_class cl ON cl.oid = co.conrelid JOIN pg_namespace n ON n.oid = cl.relnamespace
       WHERE n.nspname IN ('public','app','audit') ORDER BY 1, 2, co.contype, co.conname`);
    const pols = await q(`
      SELECT schemaname AS schema, tablename AS t, policyname, cmd, roles::text AS roles, permissive, qual, with_check
        FROM pg_policies WHERE schemaname IN ('public','app','audit') ORDER BY 1, 2, 3`);
    const trgs = await q(`
      SELECT n.nspname AS schema, c.relname AS t, t.tgname, pg_get_triggerdef(t.oid) AS def
        FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid JOIN pg_namespace n ON n.oid = c.relnamespace
       WHERE NOT t.tgisinternal AND n.nspname IN ('public','app','audit') ORDER BY 1, 2, 3`);
    const grants = await q(`
      SELECT table_schema AS schema, table_name AS t, grantee, string_agg(DISTINCT privilege_type, ', ' ORDER BY privilege_type) AS privs
        FROM information_schema.role_table_grants
       WHERE table_schema IN ('public','app','audit') AND grantee IN ('anon','authenticated')
       GROUP BY 1, 2, 3 ORDER BY 1, 2, 3`);
    const colgrants = await q(`
      SELECT table_schema AS schema, table_name AS t, grantee, privilege_type AS p, count(*)::int AS n
        FROM information_schema.column_privileges
       WHERE table_schema IN ('public','app','audit') AND grantee IN ('anon','authenticated')
       GROUP BY 1, 2, 3, 4`);
    const views = await q(`
      SELECT n.nspname AS schema, c.relname AS name,
             coalesce((SELECT option_value FROM pg_options_to_table(c.reloptions) WHERE option_name = 'security_invoker'), 'false') AS invoker
        FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
       WHERE c.relkind = 'v' AND n.nspname IN ('public','app','audit') ORDER BY 1, 2`);
    const enums = await q(`
      SELECT t.typname AS name, string_agg(e.enumlabel, ', ' ORDER BY e.enumsortorder) AS labels
        FROM pg_type t JOIN pg_enum e ON e.enumtypid = t.oid JOIN pg_namespace n ON n.oid = t.typnamespace
       WHERE n.nspname = 'public' GROUP BY 1 ORDER BY 1`);

    // ---- schema.md
    let s = banner("Database schema reference");
    const rlsOff = tables.filter((t) => !t.rls);
    s += `## Summary\n\n| Measure | Count |\n|---|---|\n`;
    s += `| Tables (public, app, audit) | ${tables.length} |\n| Tables with row-level security ON | ${tables.length - rlsOff.length} |\n`;
    s += `| Tables with RLS forced on the owner too | ${tables.filter((t) => t.forced).length} |\n| Policies | ${pols.length} |\n| Triggers | ${trgs.length} |\n| Views | ${views.length} |\n| Enum types | ${enums.length} |\n| Migration files applied | ${files.length} |\n\n`;
    s += `Tables with RLS **off**: ${rlsOff.length ? rlsOff.map((t) => `\`${t.schema}.${t.name}\``).join(", ") : "none"}.\n\n`;
    s += `## Enum types\n\n| Type | Values |\n|---|---|\n` + enums.map((e) => `| \`${e.name}\` | ${esc(e.labels)} |`).join("\n") + "\n\n";
    s += `## Views\n\n| View | security_invoker |\n|---|---|\n` + views.map((v) => `| \`${v.schema}.${v.name}\` | ${v.invoker} |`).join("\n") + "\n\n";
    s += `## Tables\n\n`;
    for (const t of tables) {
      const key = (r) => r.schema === t.schema && r.t === t.name;
      s += `### ${t.schema}.${t.name}\n\n`;
      if (t.comment) s += `${esc(t.comment)}\n\n`;
      s += `RLS: **${t.rls ? "on" : "OFF"}**${t.forced ? " (forced)" : ""}. `;
      const g = grants.filter(key);
      s += `Table grants: ${g.length ? g.map((x) => `${x.grantee}: ${x.privs}`).join("; ") : "none to anon/authenticated"}.`;
      const cg = colgrants.filter(key);
      if (cg.length) s += ` Column-level grants: ${cg.map((x) => `${x.grantee} ${x.p} on ${x.n} column(s)`).join("; ")}.`;
      s += `\n\n| Column | Type | Null | Default |\n|---|---|---|---|\n`;
      s += cols.filter((c) => c.schema === t.schema && c.t === t.name)
        .map((c) => `| \`${c.c}\` | ${esc(c.data_type === "USER-DEFINED" || c.data_type === "ARRAY" ? c.udt_name : c.data_type)}${c.is_generated === "ALWAYS" ? " (generated)" : ""} | ${c.is_nullable === "YES" ? "yes" : "no"} | ${esc(c.column_default ?? "")} |`)
        .join("\n") + "\n\n";
      const cs = cons.filter(key);
      if (cs.length) {
        const label = { p: "primary key", f: "foreign key", u: "unique", c: "check", x: "exclusion" };
        s += `| Constraint | Kind | Definition |\n|---|---|---|\n` + cs.map((c) => `| \`${c.conname}\` | ${label[c.contype] ?? c.contype} | \`${esc(c.def)}\` |`).join("\n") + "\n\n";
      }
      const ps = pols.filter(key);
      if (ps.length) {
        s += `Policies:\n\n| Policy | Command | Roles | USING | WITH CHECK |\n|---|---|---|---|---|\n`;
        s += ps.map((p) => `| \`${p.policyname}\` | ${p.cmd} | ${esc(p.roles)} | ${p.qual ? "`" + esc(p.qual) + "`" : ""} | ${p.with_check ? "`" + esc(p.with_check) + "`" : ""} |`).join("\n") + "\n\n";
      } else s += `Policies: none (with RLS on, this table is closed to anon and authenticated; only SECURITY DEFINER functions and the service role reach it).\n\n`;
      const ts = trgs.filter(key);
      if (ts.length) s += `Triggers:\n\n` + ts.map((x) => `- \`${x.tgname}\`: \`${esc(x.def.replace(/^CREATE (CONSTRAINT )?TRIGGER \S+ /, ""))}\``).join("\n") + "\n\n";
    }
    write("docs/database/generated/schema.md", s);

    // ---- functions.md
    const fns = await q(`
      SELECT n.nspname AS schema, p.proname AS name, pg_get_function_identity_arguments(p.oid) AS args,
             pg_get_function_result(p.oid) AS returns, p.prosecdef AS definer,
             coalesce(array_to_string(p.proconfig, ', '), '') AS config, p.provolatile AS vol, l.lanname AS lang,
             has_function_privilege('anon', p.oid, 'EXECUTE') AS anon_exec,
             has_function_privilege('authenticated', p.oid, 'EXECUTE') AS auth_exec,
             obj_description(p.oid, 'pg_proc') AS comment
        FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace JOIN pg_language l ON l.oid = p.prolang
       WHERE n.nspname IN ('public','app','audit') AND p.prokind = 'f'
       ORDER BY 1, 2`);
    const defNoPath = fns.filter((f) => f.definer && !/search_path/.test(f.config));
    let f = banner("Database functions reference");
    f += `## Summary\n\n| Measure | Count |\n|---|---|\n| Functions (public, app, audit) | ${fns.length} |\n| SECURITY DEFINER | ${fns.filter((x) => x.definer).length} |\n| SECURITY DEFINER without a pinned search_path | ${defNoPath.length} |\n| Executable by anon | ${fns.filter((x) => x.anon_exec).length} |\n| Executable by authenticated | ${fns.filter((x) => x.auth_exec).length} |\n\n`;
    f += `A SECURITY DEFINER function runs with its owner's rights, so each one is a door through RLS. Each checks the caller itself (usually with \`app.current_clerk_id()\` and the role helpers). Pinning \`search_path\` stops a caller from shadowing the tables it uses.\n\n`;
    for (const sc of ["public", "app", "audit"]) {
      const list = fns.filter((x) => x.schema === sc);
      f += `## Schema \`${sc}\` (${list.length})\n\n| Function | Returns | Mode | anon | authenticated |\n|---|---|---|---|---|\n`;
      f += list.map((x) => `| \`${x.name}(${esc(x.args)})\` | ${esc(x.returns)} | ${x.definer ? "DEFINER" : "invoker"}${x.definer && !/search_path/.test(x.config) ? " ⚠ no search_path" : ""} | ${x.anon_exec ? "yes" : "—"} | ${x.auth_exec ? "yes" : "—"} |`).join("\n") + "\n\n";
    }
    write("docs/database/generated/functions.md", f);
    return { tables: tables.length, rlsOff: rlsOff.map((t) => `${t.schema}.${t.name}`), pols: pols.length, fns: fns.length, definer: fns.filter((x) => x.definer).length, defNoPath: defNoPath.map((x) => `${x.schema}.${x.name}`), anonFns: fns.filter((x) => x.anon_exec && x.schema !== "audit").map((x) => `${x.schema}.${x.name}`), files: files.length };
  } finally {
    await db.end();
    await admin.query(`DROP DATABASE IF EXISTS ${SCRATCH_DB}`);
    await admin.end();
  }
}

// ---------------------------------------------------------------- routes
function walk(dir, url = [], group = "") {
  const out = [];
  const entries = readdirSync(dir);
  for (const f of entries) {
    const m = /^(page|route)\.(tsx?|jsx?)$/.exec(f);
    if (m) out.push({ path: "/" + url.join("/"), group, kind: m[1], file: relative(ROOT, join(dir, f)) });
  }
  for (const name of entries) {
    const full = join(dir, name);
    if (!statSync(full).isDirectory() || name === "fonts" || name.startsWith("_")) continue;
    const isGroup = /^\(.+\)$/.test(name);
    out.push(...walk(full, isGroup ? url : [...url, name], group || (isGroup ? name : "")));
  }
  return out;
}

async function routes() {
  const { isPublicWebsitePage, isProtectedPath, APP_ROUTE_SEGMENTS } = await import(join(ROOT, "docs/document-generation/.session-shim.mjs"));
  const all = walk(join(ROOT, "app")).sort((a, b) => a.path.localeCompare(b.path));
  const guardOf = (r, src) => {
    const g = [];
    if (isPublicWebsitePage(r.path)) g.push("public website page (Clerk middleware skipped on GET/HEAD)");
    else if (isProtectedPath(r.path)) g.push("middleware: signed-in required");
    else if (APP_ROUTE_SEGMENTS.includes(r.path.split("/").filter(Boolean)[0] ?? "")) g.push("middleware: Clerk session read, not required");
    if (/requireAdmin\(/.test(src)) g.push("page: requireAdmin");
    if (/requireFinance\(/.test(src)) g.push("page: requireFinance");
    if (/requireTeam\(/.test(src)) g.push("page: requireTeam");
    if (/cronRequestIsAuthorised/.test(src)) g.push("bearer CRON_SECRET");
    if (/verifyWebhookSignature|verifyRazorpay|x-razorpay-signature/i.test(src)) g.push("HMAC signature");
    if (/await auth\(\)/.test(src) && !g.some((x) => x.startsWith("page:"))) g.push("handler: Clerk auth()");
    if (/createAdminSupabaseClient/.test(src)) g.push("uses service role (after own checks)");
    return g.join("; ") || "—";
  };
  let r = banner("Routes reference (pages and API)");
  r += `Guards are read from \`core/auth/session.ts\` (the middleware's own functions) and from each file. "Uses service role" marks code that bypasses RLS and must do its own authorisation first; see the security chapter.\n\n`;
  for (const [title, filter] of [["Website pages", (x) => x.group === "(marketing)"], ["Sign-in pages", (x) => x.group === "(auth)"], ["Portal pages", (x) => x.group === "(app)"], ["API route handlers", (x) => x.kind === "route"], ["Other pages", (x) => !x.group && x.kind === "page"]]) {
    const list = all.filter(filter);
    r += `## ${title} (${list.length})\n\n| Path | Methods | Guard | File |\n|---|---|---|---|\n`;
    r += list.map((x) => {
      const src = readFileSync(join(ROOT, x.file), "utf8");
      const methods = x.kind === "route" ? [...src.matchAll(/export (?:async )?function (GET|POST|PUT|PATCH|DELETE|HEAD)\b/g)].map((m) => m[1]).join(", ") : "GET";
      return `| \`${x.path}\` | ${methods} | ${esc(guardOf(x, src))} | \`${x.file}\` |`;
    }).join("\n") + "\n\n";
  }
  write("docs/api/generated/routes.md", r);
  return { pages: all.filter((x) => x.kind === "page").length, api: all.filter((x) => x.kind === "route").length };
}

// ---------------------------------------------------------------- server actions
function serverActions() {
  const files = execSync(`grep -rl '"use server"' app lib`, { cwd: ROOT }).toString().trim().split("\n").filter(Boolean).sort();
  let a = banner("Server actions reference");
  a += `A server action is a function the browser calls by posting a form; it runs on the server. Each one below is listed with the database functions (RPCs) it calls, which is where the real permission checks live (SECURITY DEFINER functions and RLS), and whether it uses the service role.\n\n`;
  let total = 0;
  for (const file of files) {
    const src = readFileSync(join(ROOT, file), "utf8");
    const names = [...src.matchAll(/export async function (\w+)/g)].map((m) => m[1]);
    total += names.length;
    const rpcs = [...new Set([...src.matchAll(/\.rpc\(\s*["'`](\w+)["'`]/g)].map((m) => m[1]))].sort();
    const tables = [...new Set([...src.matchAll(/\.from\(\s*["'`](\w+)["'`]/g)].map((m) => m[1]))].sort();
    a += `### \`${file}\`\n\n- Actions (${names.length}): ${names.map((n) => `\`${n}\``).join(", ") || "—"}\n- Database functions called: ${rpcs.map((n) => `\`${n}\``).join(", ") || "—"}\n- Tables/views read or written directly: ${tables.map((n) => `\`${n}\``).join(", ") || "—"}\n- Service role: ${/createAdminSupabaseClient/.test(src) ? "**yes** (storage or a trusted write after the caller's own check)" : "no"}\n- Guards in file: ${[/await auth\(\)/.test(src) && "Clerk auth()", /requireAdmin\(/.test(src) && "requireAdmin", /requireTeam\(/.test(src) && "requireTeam", /requireFinance\(/.test(src) && "requireFinance", /rateLimit|checkRate/i.test(src) && "rate limit"].filter(Boolean).join(", ") || "via the database functions it calls"}\n\n`;
  }
  a = a.replace("\n\n", `\n\n`) + "";
  write("docs/api/generated/server-actions.md", a.replace("# Server actions reference\n\n", `# Server actions reference\n\n**${files.length} files, ${total} exported actions.**\n\n`));
  return { files: files.length, actions: total };
}

// ---------------------------------------------------------------- environment
function environment() {
  const ex = existsSync(join(ROOT, ".env.example")) ? readFileSync(join(ROOT, ".env.example"), "utf8") : "";
  const names = [...new Set([...ex.matchAll(/^\s*#?\s*([A-Z][A-Z0-9_]{2,})=/gm)].map((m) => m[1]))];
  const used = new Set(execSync(`grep -rhoE "(process\\.)?env\\.[A-Z][A-Z0-9_]+" app lib core config middleware.ts scripts`, { cwd: ROOT }).toString().match(/[A-Z][A-Z0-9_]+$/gm) ?? []);
  const all = [...new Set([...names, ...used])].filter((n) => !n.endsWith("_")).sort();
  const secret = (n) => /SECRET|KEY|TOKEN|PASSWORD|SALT|PRIVATE|DATABASE_URL|WEBHOOK/.test(n) && !/^NEXT_PUBLIC_/.test(n);
  let e = banner("Configuration variables (names only)");
  e += `Values are never written here. Secrets live in Vercel → Project → Settings → Environment Variables (and locally in an untracked \`.env.local\`). \`NEXT_PUBLIC_\` variables are built into the pages and visible to anyone; never put a secret in one.\n\n| Variable | Public? | Likely secret | In .env.example | Read in code |\n|---|---|---|---|---|\n`;
  e += all.map((n) => `| \`${n}\` | ${n.startsWith("NEXT_PUBLIC_") ? "yes (in the browser)" : "server only"} | ${secret(n) ? "yes" : "—"} | ${names.includes(n) ? "yes" : "—"} | ${used.has(n) ? "yes" : "—"} |`).join("\n") + "\n";
  write("docs/architecture/generated/environment.md", e);
  return { vars: all.length };
}

const shim = join(ROOT, "docs/document-generation/.session-shim.mjs");
writeFileSync(shim, readFileSync(join(ROOT, "core/auth/session.ts"), "utf8").replace(/ as const/g, "").replace(/\(method: string, pathname: string\): boolean/g, "(method, pathname)").replace(/\(pathname: string\): boolean/g, "(pathname)").replace(/ as readonly string\[\]/g, ""));
try {
  const out = { sha, db: await database(), routes: await routes(), actions: serverActions(), env: environment() };
  write("docs/document-generation/generated-summary.json", JSON.stringify(out, null, 2) + "\n");
} finally {
  execSync(`rm -f "${shim}"`);
}
